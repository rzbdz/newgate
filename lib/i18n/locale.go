// Package locale is the **message catalog**: user-visible text looked up by language.
//
// # Why it is a "shared leaf" and not a capability
//
// Table lookup is stateless, has no lifecycle and no owner -- installing several copies is all
// the same, and anyone may import it (see the note in docs/03-architecture.md §2, same as
// config/paths, lib/style). The capability prohibition is about services that "have an owner,
// need a start order, need to be undone in Stop"; a message table is not that kind of thing. So
// package-level functions are allowed here, and the modules/locale component only decides
// **which language gets installed** (by reading environment variables and configuration).
//
// # Key = source-language text (msgid), not a symbol
//
// The key is the English sentence written in the code: `locale.T("Proxy", nil)`. This is the
// old gettext rule, and what it buys here is **the disappearance of a whole class of failure**
// -- no keys means no "misspelled key", and therefore no easily-rotting three-way
// reconciliation between "constant <-> catalog <-> call site".
//
// The cost, plainly: changing the English wording orphans the old translation
// (`tools/i18n check` reports it, not silently). When "one sentence, two translations" is
// needed, the approach is **to write the English more specifically** (the old gettext way), not
// to introduce keys.
//
// The source language (en) **does not look anything up** at runtime: the English sentence in
// the code is the final text, and `T` only does placeholder substitution. So "default language
// = source language" is the zero-cost path, with byte-for-byte identical output to before i18n
// was added.
//
// # Why hand-rolled instead of golang.org/x/text
//
// The kernel's build and tests must be fully offline (CI runs `GOPROXY=off go test ./...`, a
// constraint pinned by docs + CI + tests together). Precedents under the same ruler: the
// runeWidth in lib/style is a hand-rolled subset of East Asian Width. This one only does four
// things: table lookup, named placeholder substitution, singular/plural choice, language tag
// matching -- enough is enough.
package i18n

import (
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"sync"
)

// SourceLang is **the language the code is written in**: the source language. It has no catalog
// file -- its "table" is the source itself (see the ledger catalogs/en.json generated by
// tools/i18n, which is only used for statistics and to show translators; the runtime does not
// need it).
const SourceLang = "en"

// A holds the arguments for named placeholders. Named (`{dir}`) rather than positional (`%s`)
// is for **translation**: English and Chinese have different word order, and named placeholders
// let translators reorder the whole sentence freely (`%[1]s` can reorder too, but nobody wants
// to count numbers inside a translation).
type A map[string]any

// Entry is one **translation**.
//
// Only one/other, no full CLDR: in this CLI the sentences that carry a count have exactly two
// forms in English ("1" and "more than 1"), and Chinese does not distinguish at all. We can
// talk about a language that really needs a third level when one shows up -- at that point the
// question is whether to pull in CLDR, not how to pile up special cases here.
type Entry struct {
	Text  string // translation with no plural variation
	One   string // plural form: 1
	Other string // plural form: the rest

	Note     string // context for translators (never enters binary output)
	Machine  bool   // machine-translated, not reviewed yet
	Reviewed bool   // reviewed by a human
}

// plural says whether this translation varies by count.
func (e Entry) plural() bool { return e.One != "" || e.Other != "" }

// Empty: an entry that is untranslated (or translated to empty) is the same as absent -- tools
// and coverage counts use it as the test.
func (e Entry) Empty() bool { return e.Text == "" && !e.plural() }

// Catalog is one language's translation table. The keys of Messages are **source-language
// text**.
type Catalog struct {
	Language string
	Source   string         // translated from which language (empty for the source table)
	Widths   map[string]int // layout widths (see Width): label / term and the like
	Messages map[string]Entry
	Builtin  bool // compiled into the binary, or picked up from disk
}

// Ledger is **the ledger**: which messages exist in the source language, what arguments and
// plural forms each takes.
//
// It is a generated artifact (`tools/i18n extract` writes it, `-check` validates it), used for
// **statistics and proofreading**: the denominator of coverage, placeholder consistency,
// orphan-key detection, input to translation tools. A copy is embedded at runtime too (it is
// small), so doctor can report "how many are translated, how many are missing" without reading
// the repository.
//
// # Why the source location is no longer recorded (the cell deleted on 2026-09-21)
//
// It used to have a `Where` cell (`file:line`), and that account came out a pure loss:
//
//   - **It had no readers.** The only thing touching it at runtime was the language health
//     check, and there it wrote `_ = le` after getting the entry -- all it wanted was "is this
//     id in the ledger". `tools/i18n check` uses the location **scanned on the spot** when
//     reporting errors, not the one in the ledger. Translation tools did not use it either.
//   - **It was the only reason the ledger went stale every day.** `check` compares the ledger
//     byte for byte, so adding one comment or moving one function in any file containing
//     `i18n.T(...)` changes the line numbers, changes the file, and turns the whole build red
//     -- **with not a single word of the message changed**. The user's own words were "every
//     time I change a bit of code it consumes a huge number of tokens to fix", and that is
//     exactly this: what was being fixed was not the copy, it was the line numbers.
//
// After the deletion the ledger only changes when **a message really changes**: one added, one
// removed, wording changed, arguments changed. That is the moment worth someone's glance
// (usually it also needs a translation), not every keypress.
type Ledger struct {
	Messages map[string]LedgerEntry
}

// LedgerEntry is one entry in the ledger.
type LedgerEntry struct {
	Args  []string // argument names given at the call site (generated)
	One   string   // singular form of a plural message (the one in the source)
	Other string   // plural form of a plural message
	Note  string   // human-written context (extract never overwrites it)
}

// Plural says whether this message varies by count.
func (e LedgerEntry) Plural() bool { return e.One != "" || e.Other != "" }

// Info is one language's **health check result**, for `newgate lang` and doctor.
//
// Why it exists: with multiple languages, "is this language actually complete" has to be
// answerable in one sentence. A missing translation is itself a fact worth stating -- falling
// back to English is fail-open, not silence.
type Info struct {
	Language   string
	Builtin    bool
	Total      int // how many entries the ledger has
	Translated int // how many are translated into this language
	Machine    int // of those, machine-translated and unreviewed
	Reviewed   int // of those, reviewed by a human
}

// ---------- installed state ----------
//
// One language is installed per process and does not change once installed (Install is called
// once by modules/locale in Start). The read path therefore only takes a read lock:
// `newgate status` looks up dozens of messages at a time, and log lines on the forwarding hot
// path look them up too -- every extra allocation there costs.

var (
	mu       sync.RWMutex
	current  = SourceLang
	table    = map[string]Entry{} // translations for the current language (empty for the source: identity)
	ledger   = map[string]LedgerEntry{}
	widths   = map[string]int{}
	builtins = map[string]Catalog{}
	overlaid int // how many keys came from a **disk overlay**
	// overlayDir is the disk override directory recorded during Install. It is kept for Use:
	// switching languages must re-read the override (`$NEWGATE_HOME/locale/<tag>.json` is **per
	// language**), and whoever calls Use (the language card on the web UI) neither should nor does
	// know where that directory is.
	overlayDir string
)

// Install installs the language this process will use and returns the tag actually in effect.
//
// led is the ledger (which messages the source language has); catalogs are the translations for
// each language (including the source language's own empty one); when diskDir is non-empty,
// `<tag>.json` from there overrides the built-ins -- "the user drops a file in and changes one
// translation without recompiling", the same culture as `~/.config/newgate/mappings/`.
//
// When the requested language does not exist it **falls back to the source language** instead
// of erroring: a user with LANG=fr_FR should not be unable to use newgate because we have not
// translated French. The fallback is visible in Info and Missing.
func Install(tag string, led Ledger, catalogs []Catalog, diskDir string) (string, error) {
	builtins = map[string]Catalog{}
	for _, c := range catalogs {
		c.Builtin = true
		if c.Messages == nil {
			c.Messages = map[string]Entry{}
		}
		builtins[c.Language] = c
	}

	mu.Lock()
	defer mu.Unlock()
	ledger = led.Messages
	overlayDir = diskDir
	return apply(tag), nil
}

// apply builds the table for the current language by tag. **The caller must already hold mu**.
//
// It only reads the already installed builtins/ledger, so "switch language" and "first
// assembly" are the same code -- written twice, the disk overlay and the "overlay only changes
// existing messages" restriction would sooner or later take effect in only one of the two
// places.
func apply(tag string) string {
	avail := make([]string, 0, len(builtins)+1)
	for lang := range builtins {
		avail = append(avail, lang)
	}
	if _, ok := builtins[SourceLang]; !ok {
		avail = append(avail, SourceLang) // the source language is always offered (no catalog needed)
	}
	sort.Strings(avail)

	eff := Match(tag, avail)
	if eff == "" {
		eff = SourceLang
	}

	next := map[string]Entry{}
	overlaid = 0
	if eff != SourceLang {
		for id, e := range builtins[eff].Messages {
			if !e.Empty() {
				next[id] = e
			}
		}
		if raw, ok := readOverlay(overlayDir, eff); ok {
			for id, e := range raw.Messages {
				if _, known := ledger[id]; !known {
					continue // an overlay may only change existing messages; invented (misspelled) ones do not apply
				}
				if e.Empty() {
					continue
				}
				next[id] = e
				overlaid++
			}
		}
	}

	current, table = eff, next
	widths = builtins[eff].Widths
	if widths == nil {
		widths = builtins[SourceLang].Widths
	}
	return eff
}

// Use switches the **current language** to another and returns the tag actually in effect. An
// empty tag falls back to the source language.
//
// Its division of labor with Install is the key to this design supporting "switch language at
// runtime":
//
//	Install  installs the **catalog tables** (which languages exist, what each translated).
//	         Once per process, modules/locale's job.
//	Use      switches to one of **the tables already installed**. Repeatable; builtins untouched.
//
// Why it must exist, rather than the caller calling Install again: Install clears and rebuilds
// builtins, and the distribution's translations are **Extend-ed in at assembly time** (a
// directory from another Go module, which the kernel does not know). Installing again wipes
// them all out -- the symptom is "after switching to Chinese on the web UI, half of the
// distribution's UI went back to English", and it looks like "a few are untranslated" rather
// than a bug.
//
// It does not write to disk: **whoever owns the preference writes it** (today only
// `newgate lang` and the language card on the web UI).
func Use(tag string) string {
	mu.Lock()
	defer mu.Unlock()
	return apply(tag)
}

// Extend **merges** another ledger and catalog into this already installed assembly.
//
// Why it is needed: Install does "resolve the language + rebuild the whole table", which should
// happen once per assembly (that is modules/locale's job). And the distribution is **another Go
// module**, whose modules have their own UI copy -- those ids are in neither the kernel's
// ledger nor the kernel's catalogs. Having the distribution call Install again would wipe the
// kernel's copy out entirely; so: installing is installing, appending is appending.
//
// When to call: after modules/locale's Start. A distribution module that writes
// `Need(localeapi.Capability)` gets that ordering edge. The language is settled by then, and
// this only fills in messages, it **does not resolve again** -- otherwise two places would each
// have their own "which one wins" priority, which would sooner or later disagree.
//
// **Same id is not overwritten**: a message the kernel already states cannot be changed by an
// append. To change the kernel's wording from the distribution, the right way is to change the
// kernel, or go through the disk overlay (the semantics of
// `~/.config/newgate/locale/<tag>.json` are "override the key of the same name"). This keeps
// "whoever owns the message decides its translation".
//
// The ledger is merged too: `newgate lang` coverage and the Missing gaps must count the
// distribution's messages, otherwise half of the distribution's UI simply does not exist on the
// dashboard.
//
// `meta.widths` is not merged: layout dimensions are a property of the **language** and belong
// to the kernel's catalogs (the same language should have the same column widths in the kernel
// and in the distribution).
func Extend(led Ledger, catalogs []Catalog) error {
	mu.Lock()
	defer mu.Unlock()
	for _, c := range catalogs {
		if c.Language == "" {
			return fmt.Errorf("the appended catalog has no meta.language")
		}
		b, known := builtins[c.Language]
		if !known {
			b = Catalog{Language: c.Language, Source: SourceLang}
		}
		if b.Messages == nil {
			b.Messages = map[string]Entry{}
		}
		for id, e := range c.Messages {
			if e.Empty() {
				continue
			}
			if _, exists := b.Messages[id]; exists {
				continue // anything the kernel already said is appended, not changed
			}
			b.Messages[id] = e
			// The source-language path is **identity** (no lookup, what the code says is the final
			// text). Writing an entry into the table would turn it into "the result of a lookup" -- and
			// that property is gone.
			if c.Language == current && current != SourceLang {
				table[id] = e
			}
		}
		builtins[c.Language] = b
	}
	for id, e := range led.Messages {
		if _, exists := ledger[id]; !exists {
			ledger[id] = e
		}
	}
	return nil
}

// T looks up one message and fills in the named placeholders.
//
// For the source language (or when nothing is found) it **uses the sentence passed in** -- this
// is not "fallback", it is identity: what the code says is the final text, and not a single map
// lookup happens (a miss is identity).
func T(msg string, args A) string { return Tn(msg, "", 0, args) }

// N is a message with a count: msg is the **singular** form (both the ledger and the catalogs
// key on it), plural is the plural form.
//
// Why both forms must be given: the source language is the identity path at runtime, so the
// program has to know how to write English plurals; the catalogs are keyed on the singular form
// (the old gettext rule). Chinese translations only need `other`.
func N(msg, plural string, n int, args A) string { return Tn(msg, plural, n, args) }

func Tn(msg, plural string, n int, args A) string {
	mu.RLock()
	e, ok := table[msg]
	lang := current
	mu.RUnlock()

	if !ok || e.Empty() {
		// Untranslated (or it is the source language): use **the sentence written at the call site**,
		// only substituting placeholders. The source language's singular/plural forms are right there
		// at the call site (`N(msg, plural, n, …)` gives both), so this path needs no catalog data at
		// all -- which is exactly why "default language = source language" costs nothing.
		if plural != "" {
			return format(pickSource(msg, plural, n), withN(args, n))
		}
		return format(msg, args)
	}
	if !e.plural() {
		// A translation with no plural forms (the common case outside Chinese, and the only case
		// in it): the count still has to reach `{n}`. Leaving out withN here made every
		// `i18n.N(...)` whose translation carried `{n}` print the placeholder literally - the
		// catalog entry passes `check` (the source has the argument) and only shows up in the
		// rendered line, so it survived until a user read `backfilled … on {n} assistant
		// messages` in the log (2026-11-19).
		//
		// Guarded on `plural`: T() reaches here through Tn(msg, "", 0, args), and there is no
		// count to inject - calling withN unconditionally would allocate a map per translated
		// string on the hot path for nothing.
		if plural != "" {
			return format(e.Text, withN(args, n))
		}
		return format(e.Text, args)
	}
	if e.One == "" || isChinese(lang) {
		// Chinese has no singular/plural distinction: writing only other is the whole story.
		if e.Other != "" {
			return format(e.Other, withN(args, n))
		}
		return format(e.One, withN(args, n))
	}
	if n == 1 {
		return format(e.One, withN(args, n))
	}
	return format(e.Other, withN(args, n))
}

// pickSource is the source language's singular/plural choice: singular for 1, plural for
// everything else (the English rule).
func pickSource(one, other string, n int) string {
	if n == 1 {
		return one
	}
	if other != "" {
		return other
	}
	return one
}

// withN puts the count into the arguments: both `{n}` in the translation and the `n` given at
// the call site are honored.
func withN(args A, n int) A {
	if _, ok := args["n"]; ok {
		return args
	}
	out := make(A, len(args)+1)
	for k, v := range args {
		out[k] = v
	}
	out["n"] = n
	return out
}

// Error is an error with a **message identity**: the copy is rendered on demand in Error().
//
// Why not let call sites write `errors.New(locale.T(...))`: then tests could only assert the
// rendered sentence (Chinese prose), which goes red when the language changes or the wording
// changes. Here the ID is language-independent, and a test writes
// `if locale.ID(err) == "cannot read mappings: {err}"` -- it asserts the identity, not the
// translation.
type Error struct {
	Msg  string // source-language text (= the message identity)
	Args A
	Err  error // optional underlying error (%w semantics)
}

func (e *Error) Error() string {
	if e == nil {
		return ""
	}
	if e.Err != nil {
		args := A{}
		for k, v := range e.Args {
			args[k] = v
		}
		args["err"] = e.Err.Error()
		return T(e.Msg, args)
	}
	return T(e.Msg, e.Args)
}

func (e *Error) Unwrap() error { return e.Err }

// E builds a translatable error. args may leave out "err", or may include it (then %w is no
// longer needed).
func E(msg string, args A) error { return &Error{Msg: msg, Args: args} }

// Ef is the way to "wrap an underlying error": `locale.Ef(err, "cannot read {path}", …)`.
func Ef(err error, msg string, args A) error {
	if err == nil {
		return nil
	}
	return &Error{Msg: msg, Args: args, Err: err}
}

// ID takes an error's **message identity** (the source-language text), for language-independent
// assertions in tests and logs. An error that is not *Error returns its own Error() text (it is
// someone else's error, passed through as is).
func ID(err error) string {
	var le *Error
	if errors.As(err, &le) {
		return le.Msg
	}
	if err == nil {
		return ""
	}
	return err.Error()
}

// ---------- query interface for upper layers ----------

// Current is the language tag currently in effect.
func Current() string {
	mu.RLock()
	defer mu.RUnlock()
	return current
}

// Width is the layout dimensions (column widths) calibrated for this language; if none are
// calibrated, the default given at the call site is used.
//
// Why width is **language data**: the label column of a `Field(...)` call fits in 8 columns in
// Chinese, and not in English ("Requests"/"Takeover") -- nothing is coded wrong, the language
// changed. Putting it in the catalog's meta means adding a language calibrates its layout along
// with it.
func Width(kind string, fallback int) int {
	mu.RLock()
	defer mu.RUnlock()
	if w, ok := widths[kind]; ok && w > 0 {
		return w
	}
	return fallback
}

// Available lists the health check result of each available language, sorted by tag. The source
// language comes first.
func Available() []Info {
	mu.RLock()
	total := len(ledger)
	langs := make([]string, 0, len(builtins)+1)
	for lang := range builtins {
		langs = append(langs, lang)
	}
	if _, ok := builtins[SourceLang]; !ok {
		langs = append(langs, SourceLang)
	}
	sort.Strings(langs)
	builtinsCopy := map[string]Catalog{}
	for k, v := range builtins {
		builtinsCopy[k] = v
	}
	mu.RUnlock()

	out := make([]Info, 0, len(langs))
	for _, lang := range langs {
		info := Info{Language: lang, Builtin: true, Total: total}
		if lang == SourceLang {
			info.Translated = total
			out = append(out, info)
			continue
		}
		for id, e := range builtinsCopy[lang].Messages {
			le, known := ledgerOf(id)
			if !known || e.Empty() {
				continue
			}
			_ = le
			info.Translated++
			switch {
			case e.Reviewed:
				info.Reviewed++
			case e.Machine:
				info.Machine++
			}
		}
		out = append(out, info)
	}
	return out
}

func ledgerOf(id string) (LedgerEntry, bool) {
	mu.RLock()
	defer mu.RUnlock()
	e, ok := ledger[id]
	return e, ok
}

// Missing lists the messages this language is still missing (relative to the ledger). For
// doctor and `newgate lang`.
func Missing(lang string) []string {
	mu.RLock()
	defer mu.RUnlock()
	if lang == SourceLang {
		return nil
	}
	c, ok := builtins[lang]
	out := make([]string, 0, len(ledger))
	for id := range ledger {
		e, ok2 := c.Messages[id]
		if !ok || !ok2 || e.Empty() {
			out = append(out, id)
		}
	}
	sort.Strings(out)
	return out
}

// Overlaid says how many keys in this assembly came from the disk overlay (0 means nobody is
// editing translations).
func Overlaid() int {
	mu.RLock()
	defer mu.RUnlock()
	return overlaid
}

// ---------- small helpers ----------

func isChinese(lang string) bool { return primary(Normalize(lang)) == "zh" }

// format substitutes `{name}`. A placeholder whose argument is not recognized is **left as
// is**: `{dir}` on the screen is ugly, but it pinpoints "one argument is missing here", which
// beats silently becoming empty.
func format(text string, args A) string {
	if len(args) == 0 || !strings.ContainsRune(text, '{') {
		return text
	}
	var b strings.Builder
	b.Grow(len(text))
	for i := 0; i < len(text); {
		c := text[i]
		if c != '{' {
			b.WriteByte(c)
			i++
			continue
		}
		end := strings.IndexByte(text[i:], '}')
		if end < 0 {
			b.WriteString(text[i:])
			break
		}
		name := text[i+1 : i+end]
		v, ok := args[name]
		if !ok || !placeholderName(name) {
			b.WriteString(text[i : i+end+1])
			i += end + 1
			continue
		}
		b.WriteString(render(v))
		i += end + 1
	}
	return b.String()
}

func render(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case string:
		return x
	case int:
		return strconv.Itoa(x)
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'f', -1, 64)
	case bool:
		return strconv.FormatBool(x)
	}
	return strings.TrimSpace(fmt.Sprint(v))
}
