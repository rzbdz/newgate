// Command genmodules scans modules/ at build time and generates the list of components the
// composition root will assemble.
//
// # Why this step exists
//
// The composition root used to maintain a hand-written `config.New(), gateway.New(), …` list.
// To install a module you had to edit that list -- and the list itself carried no information,
// it was purely a hand-kept copy of "which directories exist": add the directory, add the
// import, add the call, three places to touch, and missing one is a compile error or, worse,
// "the module is in the repository but was never assembled".
//
// So the rule became: every directory under modules/ that has a root module.go and exports
// New() is a component, and the list is generated by this tool. Installing a module = copy the
// directory in and recompile.
//
// The criteria are deliberately tight -- a directory counts only if it has module.go **and**
// that exports `func New() modules.Component` . That lets us keep pure implementation
// subpackages under modules/ (gateway/forward and such) without them being mistaken for
// components.
//
// # The list has exactly one source: this repository (since 2026-09-20)
//
// Until 2026-09-20 there was a second source here: modules-ext.json at the repo root (a Pin)
// pointing at a distribution repository, cloned into modules-ext/ at build time and scanned
// once more. That path is gone entirely, because it made **product decisions live inside the
// kernel**, and it cost three things, each measured: one distribution build dirtied the kernel
// checkout (the generated list was rewritten with the distribution's assembly list, blocking
// pull/branch switches); the kernel CI had to clone another repository; and the kernel build
// was no longer offline.
//
// Now the distribution is **another Go module** (`replace`d back to this repository), and it
// hands its own table to the kernel's composition root via app.Selection -- "which modules to
// install" is a product decision and belongs to the distribution; the kernel only needs to say
// "which ones I have" (coreModules(), with directory names) and let consumers turn some of them
// off by directory name. Criteria and reasoning: docs/09-extension-guide.md §8.
//
// So this tool is **fully offline**: no network, no other repository present. It generates two
// things, differing in who reads them:
//
//	coreModules()         the kernel's own component table (with directory names) -- for consumers
//	generatedComponents() the components the kernel's own graph installs -- for the composition root
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path"
	"path/filepath"

	modscan "github.com/rzbdz/newgate/tools/genmodules/scan"
)

const (
	modulesRelDir = "modules"
	genFileName   = "modules_gen.go"
)

// module is one component directory to be assembled.
type module struct {
	dir   string // modules/ 下的目录名，用于日志与查重
	path  string // 相对 go/ 的 import 路径后缀（`modules/foo`）
	alias string // 生成的 import 别名，统一前缀避免与局部变量撞名
}

func main() {
	check := flag.Bool("check", false,
		"只校验生成结果是否与当前源码一致，不写文件（测试用）")
	flag.Parse()

	root, err := moduleRoot()
	if err != nil {
		fail(err)
	}
	modules, err := scan(filepath.Join(root, modulesRelDir))
	if err != nil {
		fail(err)
	}
	// The generated artifact must **itself** be gofmt clean: `make check-fmt` runs separately in
	// CI, and one misaligned import block turns it red, reporting "bad formatting" -- several
	// steps away from the real cause (an alias length changed). So instead of hand-writing
	// indentation and hoping, run it through go/format.
	content, err := format.Source(render(modules))
	if err != nil {
		fail(fmt.Errorf("生成的源码不合法（这是生成器的 bug）: %w", err))
	}
	target := filepath.Join(root, "app", genFileName)

	if *check {
		current, err := os.ReadFile(target)
		if err != nil || !bytes.Equal(current, content) {
			fail(fmt.Errorf("%s 已过期：运行 `make generate`（或 go generate ./app）后重新提交", target))
		}
		return
	}
	if err := os.WriteFile(target, content, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("genmodules: %d 个组件 → %s\n", len(modules), target)
}

// moduleRoot walks up from the current working directory to the directory containing go.mod.
// `go generate` runs in the package directory (app/), `go run ./tools/genmodules` runs at the
// module root; both call sites must work, so it locates by go.mod rather than a relative path.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("向上找不到 go.mod（从 %s 开始）", dir)
		}
		dir = parent
	}
}

// scan lists every "is a component" directory name under componentsDir, in alphabetical order.
// Alphabetical rather than directory-walk order: the generated result must not depend on the
// order the filesystem returns, otherwise diffs wobble across machines.
func scan(componentsDir string) ([]module, error) {
	names, err := modscan.Dirs(componentsDir)
	if err != nil {
		return nil, err
	}
	out := make([]module, 0, len(names))
	for _, name := range names {
		// Convention: underscores in a directory name are kept in the import alias (Go identifiers
		// allow underscores)
		rel := path.Join(modulesRelDir, name)
		out = append(out, module{dir: name, path: rel, alias: modscan.Ident("mod_", name)})
	}
	return out, nil
}

// render generates the component list source.
func render(modules []module) []byte {
	const importPath = "github.com/rzbdz/newgate"

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genmodules. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// 由 `make generate`（或 go generate ./app）扫描 modules/ 得到，只有这一个来源。\n")
	b.WriteString("// 想装一个模块就把它的目录复制进 modules/、重新编译；不要手工编辑本文件。\n")
	b.WriteString("//\n")
	b.WriteString("// 发行版的模块**不在这里**：它是另一个 Go module，把自己那张表交给\n")
	b.WriteString("// app.Selection（见 docs/09-extension-guide.md §8）。\n")
	b.WriteString("\npackage app\n\n")
	b.WriteString("import (\n")
	b.WriteString("\tmodules \"")
	b.WriteString(importPath)
	b.WriteString("/component\"\n")
	for _, m := range modules {
		fmt.Fprintf(&b, "\t%s \"%s/%s\"\n", m.alias, importPath, m.path)
	}
	b.WriteString(")\n\n")
	b.WriteString("// coreModules 是内核自带的组件表，按目录名排序。\n")
	b.WriteString("//\n")
	b.WriteString("// Dir 与 Component 必须成对出现：目录名是「关掉哪一个」的键（见 app.Selection），\n")
	b.WriteString("// 组件名不必与它相同（发行版里就有：claudecode_deepseek → claudecode-deepseek）。\n")
	b.WriteString("// 内核这一侧今天恰好个个同名，那是巧合、不是规矩。\n")
	b.WriteString("func coreModules() []Entry {\n")
	b.WriteString("\treturn []Entry{\n")
	for _, m := range modules {
		fmt.Fprintf(&b, "\t\t{Dir: %q, Component: %s.New()},\n", m.dir, m.alias)
	}
	b.WriteString("\t}\n}\n\n")
	b.WriteString("// generatedComponents 是内核自己那张图要装的组件。\n")
	b.WriteString("// 顺序不是依赖声明——真实启动顺序由 capability 依赖图在构图期计算。\n")
	b.WriteString("func generatedComponents() []modules.Component {\n")
	fmt.Fprintf(&b, "\tout := make([]modules.Component, 0, %d)\n", len(modules))
	b.WriteString("\tfor _, e := range coreModules() {\n")
	b.WriteString("\t\tout = append(out, e.Component)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn out\n}\n")
	return b.Bytes()
}

// fail is the generator's exit: one sentence saying what is wrong, exit code 1.
func fail(err error) {
	fmt.Fprintln(os.Stderr, "genmodules:", err)
	os.Exit(1)
}
